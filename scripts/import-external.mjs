// Reconcile externally-registered dsh-* names into the monorepo catalog.
//
//   node scripts/import-external.mjs
//
// Paginates the npm search API for the account's packages, keeps every dsh-*
// name not already curated in catalog.mjs, and regenerates the generated
// scripts/catalog-external.mjs. npm publishing state is never touched.
import { writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { CATALOG, REAL_PACKAGES } from './catalog.mjs'

const MAINTAINER = 'dushaobindoudou'
const SEARCH = 'https://registry.npmjs.org/-/v1/search'
const SUFFIX = ' - name reserved; first release in development.'
const STANDARD_KEYWORDS = new Set(['dsh', 'dsh-plugin', 'deepseek-harness', 'cordis-plugin'])

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')

async function searchPage(from) {
  const url = `${SEARCH}?text=maintainer%3A${MAINTAINER}&size=250&from=${from}`
  const res = await fetch(url, { headers: { accept: 'application/json' } })
  if (!res.ok) throw new Error(`npm search ${res.status} at offset ${from}`)
  return res.json()
}

const objects = []
let from = 0
let total = Infinity
while (from < total) {
  const page = await searchPage(from)
  total = page.total ?? 0
  const batch = page.objects ?? []
  if (batch.length === 0) break
  objects.push(...batch)
  from += batch.length
}

const seen = new Map()
for (const o of objects) {
  const p = o.package ?? {}
  if (!p.name?.startsWith('dsh-')) continue
  if (p.publisher?.username !== undefined && p.publisher.username !== MAINTAINER) continue
  seen.set(p.name, p)
}

const external = {}
let curated = 0
for (const [name, p] of [...seen].sort(([a], [b]) => a.localeCompare(b))) {
  if (name in CATALOG || REAL_PACKAGES.includes(name)) {
    curated++
    continue
  }
  const desc = p.description ?? name
  const headline = desc.endsWith(SUFFIX) ? desc.slice(0, -SUFFIX.length) : desc
  external[name] = {
    niche: 'external waves',
    headline,
    body: `${headline}. (Recorded from the npm registry at import time.)`,
    extra: (p.keywords ?? []).filter((k) => !STANDARD_KEYWORDS.has(k)).slice(0, 6),
    version: p.version ?? '0.0.1',
  }
}

function emit(obj) {
  const lines = ['{']
  for (const [name, e] of Object.entries(obj)) {
    lines.push(`  ${JSON.stringify(name)}: {`)
    lines.push(`    niche: ${JSON.stringify(e.niche)},`)
    lines.push(`    headline: ${JSON.stringify(e.headline)},`)
    lines.push(`    body: ${JSON.stringify(e.body)},`)
    lines.push(`    extra: ${JSON.stringify(e.extra)},`)
    lines.push(`    version: ${JSON.stringify(e.version)},`)
    lines.push('  },')
  }
  lines.push('}')
  return lines.join('\n')
}

const source = `// AUTO-GENERATED by scripts/import-external.mjs - do not edit by hand.
// Externally-registered dsh-* names, reconciled from the npm registry.
// Re-run the importer after any registration wave outside this repo.
export const EXTERNAL = ${emit(external)}
`
await writeFile(join(ROOT, 'scripts', 'catalog-external.mjs'), source)

const odd = Object.values(external).filter((e) => e.version !== '0.0.1').length
console.log(`search total=${total} fetched=${objects.length} dsh=${seen.size}`)
console.log(`external entries written=${Object.keys(external).length} (already curated=${curated}, version!=0.0.1: ${odd})`)
